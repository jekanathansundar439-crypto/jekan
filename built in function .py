# Essential Built-In Functions
# These are the most common tools you'll use daily:
# print(): Displays data to the console.
# len(): Returns the number of items (length) in a string, list, or dictionary.
# type(): Identifies the data type of an object (e.g., int, str, list).
# input(): Pauses the program to get text from the user.
# range(): Generates a sequence of numbers, often used for looping.
# sum(), max(), min(): Fast mathematical operations for finding totals or extreme values in a collection.

# Data Type Conversion
# Python uses built-in "constructors" to change data from one type to another:
# int(): Converts a value to an integer.
# float(): Converts a value to a decimal number.
# str(): Converts a value to a string.
# list(), dict(), set(), tuple(): Creates or converts objects into these specific collection types.

# Functional & Advanced Helpers
# sorted(): Returns a new, sorted version of any iterable (like a list).
# enumerate(): Adds a counter to an iterable, giving you both the index and the value in loops.
# zip(): Pairs up elements from multiple lists into tuples. 
# filter() & map(): Applies logic or filters to every item in a collection.
# help(): Displays documentation for any function or object directly in your terminal
