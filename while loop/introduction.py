# WHILE LOOP
# A while loop is used to repeat a block of code again and again as long as a condition is True.
# 👉 Simple meaning:
# “Condition true ah irundha loop run aagum… false aana stop” 😄
# Syntax of while loop
# while condition:
    # code to run

# 🔹 1. break
# 👉 Used to stop the loop immediately
# 🔹 2. continue
# 👉 Used to skip current iteration and go to next loop
# 🔹3. pass
# 👉 Used when you don’t want to write code now (empty block)