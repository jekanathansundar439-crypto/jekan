# Core Casing Methods:
# upper(): Converts all characters to uppercase.
# lower(): Converts all characters to lowercase.
# capitalize(): Capitalizes only the first character of the string.
# title(): Converts the first character of each word to uppercase.
# swapcase(): Swaps uppercase to lowercase and vice versa.

# Searching and Replacing
# find(sub): Returns the lowest index where substring sub is found. Returns -1 if not found.
# index(sub): Similar to find(), but raises a ValueError if the substring is not found.
# replace(old, new): Replaces all occurrences of old with new.
# count(sub): Returns the number of times a substring appears in the string.

# Formatting and Splitting
# split(sep): Breaks a string into a list using the specified separator (default is whitespace).
# join(iterable): Concatenates a list of strings into one string, using the string it is called on as the separator.
# strip(): Removes any leading and trailing whitespace.
# format(): Formats specified values into a string using curly brace {} placeholders.

# Validation (Boolean) Methods
# isalpha(): Returns True if all characters are alphabetic.isdigit(): Returns True if all characters are digits.
# isalnum(): Returns True if all characters are alphanumeric.
# startswith(prefix): Returns True if the string starts with the specified prefix.
# endswith(suffix): Returns True if the string ends with the specified suffix.